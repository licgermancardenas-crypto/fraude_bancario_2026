# ── grafo de relaciones agregado ─────────────────────────────────────────────
# POR QUÉ EXISTE. Las tres vistas de red de este módulo —anillos, degrees del
# ranking de cuentas y vecindario de un caso— construían cada una su propio
# nx.DiGraph con `for _, row in txn.iterrows()`. A 544K transacciones el bucle
# costaba medio minuto; con el libro denso de 11,2M filas tardó 18 y 16 minutos
# los dos primeros, y el tercero —siete atributos por arista— agotó la memoria
# de la máquina: 1,5M de aristas en networkx con atributos son ~2 GB, sobre un
# equipo de 5,2 GB que ya tiene cargados el libro, el grafo PyG y el modelo.
#
# QUÉ CAMBIA EN LA SEMÁNTICA. El DiGraph ya colapsaba las aristas paralelas: al
# repetirse un par (src,dst) la última fila pisaba a la anterior, así que "el
# monto" de una relación era el de una transacción arbitraria. Sobre el libro
# denso, donde cada relación tiene 7,4 operaciones en promedio, eso pasó de ser
# un detalle a ser una cifra engañosa. Acá la agregación es explícita:
#
#     amount  = flujo total de la relación      is_fraud  = alguna marcada
#     timestamp = la operación más reciente     n_txns    = cuántas la componen
#
# Los degrees NO cambian: colapsar y agregar dan el mismo conjunto de aristas
# únicas, así que in_degree/out_degree siguen contando contrapartes distintas.
# `row` conserva la última operación del par, que es la fila que el DiGraph
# dejaba viva — de ahí salen canal/glosa/estado para la capa de presentación.
#
# No se materializa ningún objeto de grafo: todo son arrays de numpy sobre los
# códigos del Categorical, y el vecindario se resuelve con searchsorted.

class _RelGraph:
    """Aristas agregadas por par (src,dst), con búsqueda de vecindario O(log n)."""

    def __init__(self, txn):
        self.cats = txn["src"].cat.categories
        self._pos = {a: i for i, a in enumerate(self.cats)}
        n = len(self.cats)

        src = txn["src"].cat.codes.to_numpy()
        dst = txn["dst"].cat.codes.to_numpy()
        key = src.astype(np.int64) * n + dst
        del src, dst

        order = np.argsort(key, kind="stable")
        k = key[order]
        del key
        starts = np.flatnonzero(np.concatenate(([True], k[1:] != k[:-1])))
        ends   = np.concatenate((starts[1:], [len(k)]))

        self.e_key = k[starts]
        del k
        self.e_src = (self.e_key // n).astype(np.int32)
        self.e_dst = (self.e_key % n).astype(np.int32)
        self.e_amount = np.add.reduceat(
            txn["amount"].to_numpy(np.float64)[order], starts)
        self.e_ts     = np.maximum.reduceat(txn["timestamp"].to_numpy()[order], starts)
        self.e_fraud  = np.maximum.reduceat(txn["is_fraud"].to_numpy()[order], starts)
        self.e_n      = (ends - starts).astype(np.int32)
        # fila representativa = la última del par, que es la que el DiGraph dejaba
        self.e_row    = order[ends - 1].astype(np.int64)
        del order, starts, ends

        # e_src queda ordenado por construcción (key = src*n + dst) → los
        # sucesores de un nodo son un rango contiguo. Los predecesores piden un
        # segundo orden por dst.
        self._by_dst = np.argsort(self.e_dst, kind="stable")
        self._dst_sorted = self.e_dst[self._by_dst]

        self._out_deg = np.bincount(self.e_src, minlength=n)
        self._in_deg  = np.bincount(self.e_dst, minlength=n)

    # ── consultas por account_id ──────────────────────────────────────────────

    def code(self, a):
        """Índice de la cuenta en el padrón (el mismo que usan src/dst)."""
        return self._pos.get(a)

    def __contains__(self, a):
        i = self._pos.get(a)
        return i is not None and (self._out_deg[i] or self._in_deg[i])

    def out_degree(self, a):
        i = self._pos.get(a)
        return int(self._out_deg[i]) if i is not None else 0

    def in_degree(self, a):
        i = self._pos.get(a)
        return int(self._in_deg[i]) if i is not None else 0

    def _edge_pos(self, a, b):
        i, j = self._pos.get(a), self._pos.get(b)
        if i is None or j is None:
            return None
        want = np.int64(i) * len(self.cats) + j
        p = int(np.searchsorted(self.e_key, want))
        return p if p < len(self.e_key) and self.e_key[p] == want else None

    def _rec(self, p):
        return {
            "amount":    float(self.e_amount[p]),
            "timestamp": int(self.e_ts[p]),
            "is_fraud":  int(self.e_fraud[p]),
            "n_txns":    int(self.e_n[p]),
            "row":       int(self.e_row[p]),
        }

    def has_edge(self, a, b):
        return self._edge_pos(a, b) is not None

    def edge(self, a, b):
        p = self._edge_pos(a, b)
        return self._rec(p) if p is not None else None

    def successors(self, a):
        i = self._pos.get(a)
        if i is None:
            return []
        lo, hi = np.searchsorted(self.e_src, [i, i + 1])
        return [self.cats[c] for c in self.e_dst[lo:hi]]

    def predecessors(self, a):
        i = self._pos.get(a)
        if i is None:
            return []
        lo, hi = np.searchsorted(self._dst_sorted, [i, i + 1])
        return [self.cats[c] for c in self.e_src[self._by_dst[lo:hi]]]

    def out_edges(self, a):
        """[(src, dst, rec)] salientes."""
        i = self._pos.get(a)
        if i is None:
            return []
        lo, hi = np.searchsorted(self.e_src, [i, i + 1])
        return [(a, self.cats[self.e_dst[p]], self._rec(p)) for p in range(lo, hi)]

    def in_edges(self, a):
        """[(src, dst, rec)] entrantes."""
        i = self._pos.get(a)
        if i is None:
            return []
        lo, hi = np.searchsorted(self._dst_sorted, [i, i + 1])
        return [(self.cats[self.e_src[p]], a, self._rec(p))
                for p in self._by_dst[lo:hi]]

    def subgraph(self, account_ids):
        """nx.DiGraph sólo con las aristas internas al subconjunto.

        Para detección de ciclos hace falta un grafo de verdad, pero sobre las
        ~2K cuentas fraudulentas son unas pocas miles de aristas — nada que ver
        con las 1,5M del libro completo.
        """
        idx = np.array(sorted(self._pos[a] for a in account_ids if a in self._pos),
                       dtype=np.int32)
        mask = np.isin(self.e_src, idx) & np.isin(self.e_dst, idx)
        g = nx.DiGraph()
        g.add_nodes_from(self.cats[i] for i in idx)
        for p in np.flatnonzero(mask):
            g.add_edge(self.cats[self.e_src[p]], self.cats[self.e_dst[p]],
                       **self._rec(p))
        return g


class _TxnTexture:
    """Columnas de presentación (canal, glosa, estado, moneda) por fila del libro.

    El almacén columnar no guarda las derivables — a 11,2M filas serían ~700 MB
    por columna — así que `txn_store.hydrate()` las reconstruye sobre el
    subconjunto que se va a mostrar. Se memoiza por fila porque hydrate rearma el
    padrón de CBUs (75K entradas) en cada llamada y los casos piden las mismas
    filas varias veces.
    """

    def __init__(self, txn, acc):
        self._txn, self._acc, self._cache = txn, acc, {}

    def get(self, rows):
        rows = [int(r) for r in rows]
        missing = sorted({r for r in rows if r not in self._cache})
        if missing:
            sub = self._txn.iloc[missing]
            hyd = txn_store.hydrate(sub, self._acc, row_ids=np.asarray(missing))
            for r, rec in zip(missing, hyd.to_dict("records")):
                self._cache[r] = rec
        return [self._cache[r] for r in rows]

    def one(self, row):
        return self.get([row])[0]


def load_all(cfg):
    raw       = cfg["data"]["raw_dir"]
    processed = cfg["data"]["processed_dir"]

    acc = pd.read_csv(f"{raw}/accounts.csv")
    # canal/mcc/estado son categóricas de 1 byte por fila (11 MB cada una) y son
    # lo que `_TxnTexture` necesita para reconstruir el extracto de un caso: sin
    # ellas el legajo pierde canal, concepto y estado de cada operación.
    txn = txn_store.load_transactions(
        raw,
        columns=["src", "dst", "amount", "timestamp", "transaction_type",
                 "is_fraud", "canal", "mcc", "estado"],
        with_row_id=True,
    )

    data = torch.load(f"{processed}/graph.pt", weights_only=False)

    ckpt  = torch.load("models/graphsage_best.pt", weights_only=False)
    model = GraphSAGE(data.num_node_features, **{
        k: ckpt["config"][k] for k in ["hidden_channels", "num_layers", "dropout"]
    })
    model.load_state_dict(ckpt["model_state"])
    model.eval()

    with torch.no_grad():
        scores_all = F.softmax(model(data.x, data.edge_index), dim=1)[:, 1].numpy()

    scores_by_model = {}
    for name, fname in MODEL_SCORE_FILES.items():
        path = Path(processed) / fname
        if path.exists():
            scores_by_model[name] = np.load(path)
        else:
            print(f"  (omitido: {name} — {fname} no encontrado)")
    scores_gnn = scores_by_model["GraphSAGE"]
    y_test     = np.load(f"{processed}/y_test.npy")

    return acc, txn, data, scores_all, scores_by_model, scores_gnn, y_test


# ── 1. kpis.json ─────────────────────────────────────────────────────────────

def export_kpis(acc, data, scores_gnn, y_test, out_dir):
    n_accounts   = int(data.num_nodes)
    n_fraud      = int((data.y == 1).sum())
    pct_fraud    = round(100 * n_fraud / n_accounts, 2)
    pr_auc_gnn   = round(float(average_precision_score(y_test, scores_gnn)), 4)
    rec_p90, _   = recall_at_precision(y_test, scores_gnn, 0.90)

    obj = {
        "n_accounts":   n_accounts,
        "n_fraud":      n_fraud,
        "pct_fraud":    pct_fraud,
        "pr_auc_gnn":   pr_auc_gnn,
        "recall_at_p90": round(float(rec_p90), 4),
        "model":        "GraphSAGE (2 capas, 64 hidden)",
        "dataset":      "Sintético — Santander AI Lab equiv.",
        "client":       "Banco Regional del Sur (BRS)",
    }
    _save(obj, f"{out_dir}/kpis.json")


# ── 2. pr_curves.json ────────────────────────────────────────────────────────

def export_pr_curves(y_test, scores_by_model, out_dir):
    def _curve(y, s, name):
        prec, rec, _ = precision_recall_curve(y, s)
        # downsample to ≤200 points to keep JSON small
        step = max(1, len(prec) // 200)
        return {
            "model":    name,
            "pr_auc":   round(float(average_precision_score(y, s)), 4),
            "precision": [round(float(p), 4) for p in prec[::step]],
            "recall":    [round(float(r), 4) for r in rec[::step]],
        }

    obj = [_curve(y_test, scores, name) for name, scores in scores_by_model.items()]
    _save(obj, f"{out_dir}/pr_curves.json")


# ── 3. score_distribution.json ────────────────────────────────────────────────

def export_score_distribution(data, scores_all, out_dir, n_bins=40):
    y_all    = data.y.numpy()
    bins     = np.linspace(0, 1, n_bins + 1)
    centers  = ((bins[:-1] + bins[1:]) / 2).tolist()

    fraud_hist, _ = np.histogram(scores_all[y_all == 1], bins=bins, density=False)
    legit_hist, _ = np.histogram(scores_all[y_all == 0], bins=bins, density=False)

    obj = {
        "bin_centers": [round(c, 3) for c in centers],
        "fraud":       fraud_hist.tolist(),
        "legit":       legit_hist.tolist(),
    }
    _save(obj, f"{out_dir}/score_distribution.json")


# ── 4. rings.json ─────────────────────────────────────────────────────────────

def export_rings(acc, rel, data, scores_all, out_dir, top_n=10):
    node_ids  = data.node_ids
    id2score  = {nid: float(scores_all[i]) for i, nid in enumerate(node_ids)}
    fraud_set = set(acc.loc[acc.is_fraud == 1, "account_id"])
    acc_idx   = acc.set_index("account_id")

    # Los ciclos se buscan sólo sobre el subgrafo fraudulento, que es lo que el
    # código hacía igual (G.subgraph(fraud_set)) pero después de haber armado el
    # grafo entero. Acá se arma directamente el chico.
    Gf = rel.subgraph(fraud_set)
    rings = []
    try:
        for cycle in nx.simple_cycles(Gf):
            if 3 <= len(cycle) <= 10:
                rings.append(cycle)
                if len(rings) >= top_n:
                    break
    except Exception:
        pass

    out_rings = []
    for i, ring in enumerate(rings):
        nodes_data = []
        for nid in ring:
            row = acc_idx.loc[nid]
            nodes_data.append({
                "id":           nid,
                "gnn_score":    round(id2score.get(nid, 0.0), 4),
                "is_fraud":     int(row.is_fraud),
                "balance":      round(float(row.balance), 2),
                "risk_score":   round(float(row.risk_score), 4),
                "account_type": row.account_type,
            })

        ring_edges = []
        total_amount = 0.0
        for j in range(len(ring)):
            src, dst = ring[j], ring[(j+1) % len(ring)]
            ed = rel.edge(src, dst)
            if ed is not None:
                amt = round(float(ed["amount"]), 2)
                ring_edges.append({"src": src, "dst": dst, "amount": amt,
                                   "n_txns": ed["n_txns"]})
                total_amount += amt

        out_rings.append({
            "ring_id":      i + 1,
            "n_nodes":      len(ring),
            "total_amount": round(total_amount, 2),
            "avg_score":    round(np.mean([n["gnn_score"] for n in nodes_data]), 4),
            "nodes":        nodes_data,
            "edges":        ring_edges,
        })

    _save(out_rings, f"{out_dir}/rings.json")


# ── 5. top_accounts.json ──────────────────────────────────────────────────────

def export_top_accounts(acc, feats, rel, data, scores_all, out_dir, top_n=200):
    node_ids = data.node_ids

    fraud_set  = set(acc.loc[acc.is_fraud == 1, "account_id"])
    acc_idx    = acc.set_index("account_id")
    feats_idx  = feats.set_index("account_id")

    records = []
    for i, nid in enumerate(node_ids):
        row = acc_idx.loc[nid]
        f   = feats_idx.loc[nid] if nid in feats_idx.index else None
        records.append({
            "account_id":       nid,
            "gnn_score":        round(float(scores_all[i]), 4),
            "is_fraud":         int(row.is_fraud),
            "balance":          round(float(row.balance), 2),
            "risk_score":       round(float(row.risk_score), 4),
            "account_type":     row.account_type,
            "degree_in":        rel.in_degree(nid),
            "degree_out":       rel.out_degree(nid),
            "total_sent":       round(float(f["total_sent"]) if f is not None else 0, 2),
            "total_received":   round(float(f["total_received"]) if f is not None else 0, 2),
            "in_ring":          nid in fraud_set,
        })

    records.sort(key=lambda r: r["gnn_score"], reverse=True)
    _save(records[:top_n], f"{out_dir}/top_accounts.json")


# ── 6. entities.json ──────────────────────────────────────────────────────────

def export_entities(acc, txn, data, scores_all, cfg, out_dir, top_n=300):
    """
    Build entity network JSON for Cytoscape visualization.
    Focuses on top_n accounts by GNN score + their entity relationships.
    Node types: cuenta | persona | empresa
    Edge types: es_titular | es_director | transaccion
    """
    raw = cfg["data"]["raw_dir"]
    personas, empresas, titularidades, directores, pep_flags, _sanctions = _load_entity_tables(raw)

    node_ids = data.node_ids
    id2score = {nid: float(scores_all[i]) for i, nid in enumerate(node_ids)}
    acc_idx  = acc.set_index("account_id")

    # top accounts to include in the entity network
    sorted_accs = sorted(node_ids, key=lambda x: id2score.get(x, 0), reverse=True)
    top_accs = set(sorted_accs[:top_n])

    pep_set = set(pep_flags["account_id"].tolist()) if not pep_flags.empty else set()
    personas_idx = personas.set_index("account_id") if not personas.empty else pd.DataFrame()
    emp_idx = empresas.set_index("empresa_id") if not empresas.empty else pd.DataFrame()

    nodes, edges = [], []
    seen_nodes, seen_edges = set(), set()

    def _add_node(node_id, node_type, props):
        if node_id not in seen_nodes:
            seen_nodes.add(node_id)
            nodes.append({"id": node_id, "type": node_type, **props})

    def _add_edge(src, dst, rel_type, props=None):
        key = (src, dst, rel_type)
        if key not in seen_edges:
            seen_edges.add(key)
            edges.append({"src": src, "dst": dst, "type": rel_type, **(props or {})})

    # add account nodes
    for acc_id in top_accs:
        row = acc_idx.loc[acc_id]
        persona_info = {}
        if not personas_idx.empty and acc_id in personas_idx.index:
            p = personas_idx.loc[acc_id]
            persona_info = {
                "nombre_completo": str(p.get("nombre_completo", "")),
                "ocupacion":       str(p.get("ocupacion", "")),
                "municipio":       str(p.get("municipio", "")),
                "cuil":            str(p.get("cuil", "")),
            }
        _add_node(acc_id, "cuenta", {
            "label":        persona_info.get("nombre_completo", acc_id),
            "gnn_score":    round(id2score.get(acc_id, 0), 4),
            "is_fraud":     int(row.is_fraud),
            "balance":      round(float(row.balance), 2),
            "risk_score":   round(float(row.risk_score), 4),
            "account_type": row.account_type,
            "is_pep":       acc_id in pep_set,
            **persona_info,
        })

    # titularidades: link empresas to top accounts
    if not titularidades.empty:
        emp_titularidades = titularidades[
            (titularidades["titular_type"] == "empresa") &
            (titularidades["account_id"].isin(top_accs))
        ]
        for _, row in emp_titularidades.iterrows():
            emp_id = row["titular_id"]
            if not emp_idx.empty and emp_id in emp_idx.index:
                emp = emp_idx.loc[emp_id]
                _add_node(emp_id, "empresa", {
                    "label":             str(emp["razon_social"]),
                    "razon_social":      str(emp["razon_social"]),
                    "cuit_empresa":      str(emp["cuit_empresa"]),
                    "sector":            str(emp["sector"]),
                    "pais_constitucion": str(emp["pais_constitucion"]),
                    "is_shell":          bool(emp["is_shell"]),
                })
                _add_edge(emp_id, row["account_id"], "es_titular", {
                    "porcentaje": int(row.get("porcentaje_titularidad", 100))
                })

    # directores: link personas (accounts) to empresas in network
    if not directores.empty and not emp_idx.empty:
        visible_emps = {n["id"] for n in nodes if n["type"] == "empresa"}
        dir_links = directores[
            (directores["persona_id"].isin(top_accs)) &
            (directores["empresa_id"].isin(visible_emps))
        ]
        for _, row in dir_links.iterrows():
            _add_edge(row["persona_id"], row["empresa_id"], "es_director", {
                "cargo": str(row["cargo"]),
                "vigente": bool(row.get("vigente", True)),
            })

    _save({"nodes": nodes, "edges": edges}, f"{out_dir}/entities.json")


# ── 7. cases.json ─────────────────────────────────────────────────────────────

def export_cases(acc, txn, feats, rel, texture, data, scores_all, cfg, out_dir,
                 n_cases=80):
    """
    Pre-generate alert cases for the case management module.
    Takes top scored accounts + all confirmed fraud nodes.
    Each case includes full context: entity, transactions, neighbors, pattern.
    """
    raw = cfg["data"]["raw_dir"]
    seed = cfg["project"]["seed"]
    rng = np.random.default_rng(seed + 99)
    random.seed(seed + 99)

    personas, empresas, titularidades, directores, pep_flags, sanctions_hits = _load_entity_tables(raw)

    node_ids = data.node_ids
    id2idx   = {nid: i for i, nid in enumerate(node_ids)}
    id2score = {nid: float(scores_all[i]) for i, nid in enumerate(node_ids)}
    acc_idx  = acc.set_index("account_id")

    personas_idx = personas.set_index("account_id") if not personas.empty else pd.DataFrame()
    emp_idx      = empresas.set_index("empresa_id") if not empresas.empty else pd.DataFrame()
    pep_set      = set(pep_flags["account_id"].tolist()) if not pep_flags.empty else set()
    # account_id → hit de screening (a lo sumo uno por cuenta, ver generate_sanctions_hits)
    sanctions_idx = (
        {r["account_id"]: r for r in sanctions_hits.to_dict("records")}
        if not sanctions_hits.empty else {}
    )

    # ── rules engine: deterministic AML scenarios evaluated alongside the GNN ──
    # Dos motores complementarios: el agregado (R01-R07) sobre las features de
    # cuenta y el temporal (R09-R13) sobre el stream, que además cita las
    # operaciones concretas que dispararon cada escenario.
    rules_by_acc = rules_engine.evaluate(feats, cfg)
    temporal_by_acc = rules_temporal.evaluate(txn, acc, cfg)

    n_txn_rows = len(txn)

    def _evidence_txns(txn_ids):
        """Operaciones citadas por un escenario, listas para mostrar en el ROS."""
        # transaction_id ES la posición de la fila en el libro (ver txn_store):
        # se accede por iloc en vez de indexar el frame de 11,2M filas por esa
        # columna, que era lo que hacía `txn.set_index("transaction_id")`.
        rows = [int(t) for t in txn_ids[:12]   # tope: evidencia ilustrativa, no el extracto
                if 0 <= int(t) < n_txn_rows]
        if not rows:
            return []
        out = []
        for r in texture.get(rows):
            out.append({
                "transaction_id": r["transaction_id"],
                "src": str(r["src"]), "dst": str(r["dst"]),
                "amount": round(float(r["amount"]), 2),
                "timestamp": int(r["timestamp"]),
                "tipo": str(r["transaction_type"]),
                "canal": str(r["canal"]),
                "glosa": str(r["glosa"]),
            })
        return out

    def _rules(acc_id, screening):
        """Escenarios disparados: agregados (R01-R07), temporales (R09-R13) y R08."""
        ids = list(rules_by_acc.get(acc_id, {}).get("rules_fired", []))
        if screening.get("hit_directo") or screening.get("exposicion_indirecta"):
            ids.append("R08")  # sanctions/watchlist exposure
        temporal = temporal_by_acc.get(acc_id, {})
        ids += list(temporal.get("rules_fired", []))

        evidencia = temporal.get("evidence", {})
        rules_fired = []
        for rid in ids:
            meta = rules_engine.RULES_BY_ID[rid]
            entry = {k: meta[k] for k in ("id", "nombre", "cita", "severidad",
                                          "descripcion", "motor")}
            if rid in evidencia:
                ev = dict(evidencia[rid])
                entry["evidencia"] = {
                    **{k: v for k, v in ev.items() if k != "operaciones"},
                    "operaciones": _evidence_txns(ev.get("operaciones", [])),
                }
            rules_fired.append(entry)
        return {"rules_fired": rules_fired,
                "rule_score": rules_engine.score_from_ids(ids, cfg)}

    # candidate accounts: all fraud + top scored legit (high-risk alerts)
    fraud_ids = set(acc.loc[acc.is_fraud == 1, "account_id"])
    sorted_by_score = sorted(node_ids, key=lambda x: id2score.get(x, 0), reverse=True)
    candidates = list(dict.fromkeys(
        [x for x in sorted_by_score if x in fraud_ids] +
        sorted_by_score[:n_cases]
    ))[:n_cases]

    # ground-truth typology from the generator (accounts.csv), when present
    typ_map = (
        acc.set_index("account_id")["fraud_typology"].fillna("").to_dict()
        if "fraud_typology" in acc.columns else {}
    )

    def _pattern(acc_id):
        # prefer the labelled typology emitted by the generator
        label = typ_map.get(acc_id) or ""
        if label:
            return label
        # fallback heuristic for high-scored accounts without a ground-truth label
        nbrs = rel.predecessors(acc_id) + rel.successors(acc_id)
        nbr_fraud = sum(1 for n in nbrs if n in fraud_ids)
        if nbr_fraud >= 3:
            return "anillo_lavado"
        out_txns = [d["amount"] for _s, _d, d in rel.out_edges(acc_id)]
        if len(out_txns) >= 4 and max(out_txns, default=0) < 10000:
            return "estructuracion"
        if rel.in_degree(acc_id) >= 5:
            return "agregacion_fondos"
        return "transacciones_inusuales"

    def _empresa_info(acc_id):
        if titularidades.empty:
            return None
        row = titularidades[
            (titularidades["account_id"] == acc_id) &
            (titularidades["titular_type"] == "empresa")
        ]
        if row.empty:
            return None
        emp_id = row.iloc[0]["titular_id"]
        if emp_idx.empty or emp_id not in emp_idx.index:
            return None
        e = emp_idx.loc[emp_id]
        return {
            "empresa_id":      emp_id,
            "razon_social":    str(e["razon_social"]),
            "cuit_empresa":    str(e["cuit_empresa"]),
            "sector":          str(e["sector"]),
            "pais_constitucion": str(e["pais_constitucion"]),
            "is_shell":        bool(e["is_shell"]),
        }

    def _neighbors(acc_id, top_k=6):
        preds = set(rel.predecessors(acc_id))
        nbrs = list((preds | set(rel.successors(acc_id))) - {acc_id})
        nbrs.sort(key=lambda x: id2score.get(x, 0), reverse=True)
        result = []
        for n in nbrs[:top_k]:
            direction = "entrada" if n in preds else "salida"
            ed = rel.edge(n, acc_id) if direction == "entrada" else rel.edge(acc_id, n)
            result.append({
                "account_id": n,
                "gnn_score":  round(id2score.get(n, 0), 4),
                "is_fraud":   int(acc_idx.loc[n, "is_fraud"]) if n in acc_idx.index else 0,
                "direction":  direction,
                "amount":     round(ed["amount"] if ed else 0, 2),
                "n_txns":     ed["n_txns"] if ed else 0,
            })
        return result

    def _screening(acc_id, neighbors):
        """
        Screening de sanciones — hit directo sobre la cuenta + exposición
        indirecta (la cuenta transaccionó con alguien que sí está en una
        lista). Es la capacidad que la landing promete: no solo alertar al
        que está en la lista, sino a quien está a un salto de distancia.
        """
        direct = sanctions_idx.get(acc_id)
        indirecta = []
        for n in neighbors:
            h = sanctions_idx.get(n["account_id"])
            if h:
                indirecta.append({
                    "account_id":          n["account_id"],
                    "direction":           n["direction"],
                    "lista":               h["lista"],
                    "nombre_coincidencia": h["nombre_coincidencia"],
                    "motivo":              h["motivo"],
                    "score_match":         round(float(h["score_match"]), 2),
                    "estado":              h["estado"],
                })
        return {
            "hit_directo": ({
                "lista":               direct["lista"],
                "nombre_coincidencia": direct["nombre_coincidencia"],
                "motivo":              direct["motivo"],
                "score_match":         round(float(direct["score_match"]), 2),
                "estado":              direct["estado"],
            } if direct is not None else None),
            "exposicion_indirecta": indirecta,
        }

    def _dst_type(dst):
        return acc_idx.loc[dst, "account_type"] if dst in acc_idx.index else None

    def _edge_meta(d):
        """Campos de presentación de la operación representativa de la relación.

        Una relación agregada no tiene un canal único —son 7,4 operaciones en
        promedio— así que se muestra el de la última, que es exactamente la fila
        que el DiGraph anterior dejaba viva al colapsar las aristas paralelas.
        """
        r = texture.one(d["row"])
        return {
            "canal":    str(r["canal"]),
            "concepto": str(r["glosa"]),
            "moneda":   str(r["moneda"]),
            "estado":   str(r["estado"]),
        }

    src_codes = np.asarray(txn["src"].cat.codes)
    dst_codes = np.asarray(txn["dst"].cat.codes)
    ts_all    = txn["timestamp"].to_numpy()

    def _recent_txns(acc_id, top_k=10):
        """Últimos movimientos reales de la cuenta, no las relaciones agregadas.

        Sobre el libro denso una cuenta tiene cientos de operaciones repartidas
        entre unas pocas decenas de contrapartes recurrentes: listar las aristas
        agregadas daría un extracto sin fechas propias, con una línea por
        contraparte. El legajo quiere el movimiento, así que se filtra el libro
        por la cuenta y se toman los más recientes.
        """
        i = rel.code(acc_id)
        if i is None:
            return []
        hit = np.flatnonzero((src_codes == i) | (dst_codes == i))
        if hit.size == 0:
            return []
        top = hit[np.argsort(ts_all[hit], kind="stable")[::-1][:top_k]]
        rows = []
        for r in texture.get(top):
            rows.append({
                "src": str(r["src"]), "dst": str(r["dst"]),
                "amount":    round(float(r["amount"]), 2),
                "timestamp": int(r["timestamp"]),
                "direction": "salida" if str(r["src"]) == acc_id else "entrada",
                "is_fraud":  int(r["is_fraud"]),
                "canal":     str(r["canal"]),
                "concepto":  str(r["glosa"]),
                "moneda":    str(r["moneda"]),
                "estado":    str(r["estado"]),
            })
        return rows

    # ── traceability: multi-hop money trail (upstream to origin + layering out) ──
    perp_set = set()
    ot_path = Path(out_dir) / "origin_trace.json"
    if ot_path.exists():
        try:
            perp_set = {p["node_id"] for p in json.loads(ot_path.read_text())["perpetrators"]}
        except Exception:
            perp_set = set()

    def _name(nid):
        if not personas_idx.empty and nid in personas_idx.index:
            v = personas_idx.loc[nid].get("nombre_completo")
            return str(v) if pd.notna(v) else None
        return None

    def _hop(src, dst):
        d = rel.edge(src, dst)
        hop = {
            "from": src, "to": dst,
            "amount": round(float(d["amount"]), 2),
            "timestamp": int(d["timestamp"]),
            "is_fraud_edge": int(d["is_fraud"]),
        }
        hop.update(_edge_meta(d))
        return hop

    def _traceability(acc_id, max_depth=6):
        """
        Reconstruct the money trail around a case account:
          - upstream: walk backward along the largest *fraudulent* inflow, hop by
            hop, until reaching an origin (a known perpetrator or a node with no
            fraudulent inflow). Cycle-safe (round-tripping schemes are cyclic).
          - downstream: the layering exits — outgoing edges, largest first.
        Returns ordered hops (origin first → case account → exits).
        """
        upstream, visited, cur = [], {acc_id}, acc_id
        for _ in range(max_depth):
            in_edges = [(s, d) for s, _t, d in rel.in_edges(cur) if s not in visited]
            fraud_in = [(s, d) for s, d in in_edges if d["is_fraud"] == 1]
            pool = fraud_in or [(s, d) for s, d in in_edges
                                if s in fraud_ids or id2score.get(s, 0) > 0.5]
            if not pool:
                break
            s, _d = max(pool, key=lambda x: x[1]["amount"])
            hop = _hop(s, cur)
            hop.update({
                "from_gnn_score": round(id2score.get(s, 0), 4),
                "from_is_fraud":  int(acc_idx.loc[s, "is_fraud"]) if s in acc_idx.index else 0,
                "from_is_perp":   s in perp_set,
                "from_name":      _name(s),
            })
            upstream.append(hop)
            visited.add(s)
            cur = s
            if s in perp_set:
                break
        upstream.reverse()  # origin first → case account last

        out_edges = sorted(
            ((dst, d) for _s, dst, d in rel.out_edges(acc_id)),
            key=lambda x: x[1]["amount"], reverse=True,
        )
        downstream = []
        for dst, _d in out_edges[:6]:
            hop = _hop(acc_id, dst)
            hop.update({
                "to_gnn_score": round(id2score.get(dst, 0), 4),
                "to_is_fraud":  int(acc_idx.loc[dst, "is_fraud"]) if dst in acc_idx.index else 0,
                "to_name":      _name(dst),
            })
            downstream.append(hop)

        origin = None
        if upstream:
            h = upstream[0]
            origin = {
                "account_id": h["from"], "gnn_score": h["from_gnn_score"],
                "is_fraud": h["from_is_fraud"], "is_perp": h["from_is_perp"],
                "name": h["from_name"], "amount": h["amount"],
            }
        return {"upstream": upstream, "downstream": downstream, "origin": origin}

    # Fechas de alerta repartidas en una ventana amplia (~6 meses) para que los
    # plazos ROS (alerta + 150 días) caigan escalonados y la cola tenga aging
    # realista: casos vencidos, por vencer y con holgura, no todos "recientes".
    base_date = datetime(2026, 2, 1)

    # Ley 25.246 (UIF Argentina), art. 21 inc. b — plazo máximo para que un
    # sujeto obligado reporte una Operación Sospechosa (ROS) desde que la
    # detecta: 150 días corridos para entidades financieras/bancarias.
    DIAS_PLAZO_ROS = 150

    # Pool de analistas de compliance (ficticio) — asignación determinística
    # por caso, no por cuenta, para distribuir la carga de forma pareja.
    ANALISTAS = [
        "Lic. Valentina Ibarra",
        "Lic. Tomás Ferreyra",
        "Lic. Camila Suárez",
        "Lic. Nicolás Paredes",
        "Lic. Agustina Domínguez",
    ]

    cases = []
    for i, acc_id in enumerate(candidates):
        row = acc_idx.loc[acc_id]
        persona = {}
        if not personas_idx.empty and acc_id in personas_idx.index:
            p = personas_idx.loc[acc_id]
            persona = {k: str(p[k]) if pd.notna(p[k]) else "" for k in p.index}

        alert_dt   = base_date + timedelta(days=int(rng.integers(0, 190)))
        alert_date = alert_dt.strftime("%Y-%m-%d")
        vencimiento_ros = (alert_dt + timedelta(days=DIAS_PLAZO_ROS)).strftime("%Y-%m-%d")
        score = id2score.get(acc_id, 0)
        neighbors = _neighbors(acc_id)
        screening = _screening(acc_id, neighbors)
        rules = _rules(acc_id, screening)

        cases.append({
            "case_id":      f"CASO-{i+1:05d}",
            "account_id":   acc_id,
            "gnn_score":    round(score, 4),
            "is_fraud":     int(row.is_fraud),
            "alert_date":   alert_date,
            "status":       "abierto",
            "pattern":      _pattern(acc_id),
            "is_pep":       acc_id in pep_set,
            "balance":      round(float(row.balance), 2),
            "risk_score":   round(float(row.risk_score), 4),
            "account_type": row.account_type,
            "analista_asignado": ANALISTAS[int(rng.integers(0, len(ANALISTAS)))],
            "dias_plazo_ros":    DIAS_PLAZO_ROS,
            "vencimiento_ros":   vencimiento_ros,
            "screening":    screening,
            "rule_score":   rules["rule_score"],
            "rules_fired":  rules["rules_fired"],
            "persona":      persona,
            "empresa":      _empresa_info(acc_id),
            "neighbors":    neighbors,
            "recent_transactions": _recent_txns(acc_id),
            "traceability": _traceability(acc_id),
        })

    _save(cases, f"{out_dir}/cases.json")
    _save(rules_engine.catalogue(), f"{out_dir}/rules_catalog.json")

    n_with_rules = sum(1 for c in cases if c["rules_fired"])
    n_temporal = sum(1 for c in cases
                     if any(r.get("motor") == "temporal" for r in c["rules_fired"]))
    n_evid = sum(1 for c in cases if any("evidencia" in r for r in c["rules_fired"]))
    print(f"  reglas AML: {n_with_rules}/{len(cases)} casos con >=1 escenario disparado "
          f"({n_temporal} con escenario temporal, {n_evid} con evidencia citada)")


